class TestScoring:
    """Tests for accessibility scoring."""

    @pytest.fixture
    def checker(self):
        return LUIAccessibilityChecker()

    def test_perfect_score(self, checker: LUIAccessibilityChecker):
        """Test perfect score for simple text."""
        result = checker.check_response("Hello. How are you?", ComplianceLevel.LEVEL_A)

        # Very simple text should have high score
        assert result.score >= 0.9

    def test_score_decreases_with_violations(self, checker: LUIAccessibilityChecker):
        """Test score decreases as violations increase."""
        simple_result = checker.check_response("The cat sat.", ComplianceLevel.LEVEL_AA)
        complex_result = checker.check_response(COMPLEX_TEXT, ComplianceLevel.LEVEL_AA)

        # More violations = lower score
        assert simple_result.score >= complex_result.score

    def test_score_weights_correct(self, checker: LUIAccessibilityChecker):
        """Test that severity weights are applied correctly."""
        # One critical violation should reduce score by 0.25
        result = checker.check_response(COMPLEX_TEXT, ComplianceLevel.LEVEL_A)

        # Calculate expected score reduction
        total_weight = sum(v.weight for v in result.violations)
        expected_score = max(0.0, 1.0 - total_weight)

        assert result.score == expected_score

    def test_score_minimum_is_zero(self, checker: LUIAccessibilityChecker):
        """Test score doesn't go below zero."""
        # Very problematic text
        problematic = LONG_SENTENCE + " " + COMPLEX_TEXT + " " + PASSIVE_VOICE_TEXT

        result = checker.check_response(problematic, ComplianceLevel.LEVEL_AAA)

        assert result.score >= 0.0


